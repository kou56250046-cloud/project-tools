// フロー記法の説明（Gemini に業務フロー・判断の流れを書かせるときに指示文へ入れる）
// 写した部品: gemini-kit src/items/50-fmt-flow.md（2026-11-26）。キットのタブの話を外し、参照の ID を台帳の ID に直した

import { KINDS } from './schema.js';

const refKinds = () => ['question', 'requirement', 'decision', 'issue'].map((k) => `${KINDS[k].prefix}-（${KINDS[k].label}）`).join('・');

export function flowFormatText() {
  return [
    '# フロー記法',
    '業務フローや処理の流れは、次の「フロー記法」で書いてください。座標や見た目は書かないでください。配置は描画ツールが自動で行います。',
    'Mermaid・PlantUML など、ほかの記法で書かないでください。',
    '',
    '## 書き方の例',
    'title 受注処理フロー（現行）',
    'lane 顧客',
    'lane 営業部',
    'lane 基幹システム',
    '',
    'start S @顧客 発注を決める',
    'task A @顧客 注文書を送付',
    'task B @営業部 注文内容を確認',
    'decision C @営業部 不備はあるか',
    'data D @基幹システム 受注データ登録',
    'doc E @基幹システム 出荷指示書',
    'end Z @顧客 商品を受け取る',
    '',
    'S -> A -> B -> C',
    'C -> A : あり',
    'C -> D : なし',
    'D -> E -> Z',
    'E ..> B : 控えを送付',
    'note C 不備の基準は別紙',
    '',
    '## 行の種類',
    '- タイトル: `title 文字`（省略可）',
    '- レーン: `lane 名前` または `lane 名前 {区分}`。担当者・部署・システム。上から順に並ぶ',
    '- ノード: `種類 ID @レーン ラベル` または `種類 ID @レーン {区分} ラベル`。ID は半角英数字（例: A, B2, S1）。ラベルは日本語で 15 字程度まで',
    '- 矢印: `ID -> ID` または `ID -> ID : ラベル`。`A -> B -> C` と続けても書ける',
    '- 点線の矢印: `ID ..> ID : ラベル`（情報・書類の流れ、後日の処理など）',
    '- 注記: `note ID 文字`（図の下に ※番号で載る）',
    '- コメント: `# 文字`（無視される）',
    '',
    '## ノードの種類',
    '- `start` 開始 / `end` 終了 / `task` 作業・処理 / `decision` 分岐（出る矢印には必ず `: はい` `: いいえ` などのラベルを付ける）',
    '- `data` データの登録・入出力 / `doc` 帳票・書類の出力 / `sub` 別のフローで詳しく書く処理',
    '',
    '## 処理の区分（AI・ルール・人・外部）',
    '誰（何）がその処理をするかを `{区分}` で書くと、区分ごとに決まった色で描かれ、箱の左上に区分名が付きます。',
    '- `{AI}`: 生成 AI・AI エージェントが読み取り・要約・判断する処理（分岐なら AI 判断）',
    '- `{ルール}`: Power Automate・マクロ・システムなど、決まった規則で動く処理（分岐ならルール判定。明確な条件で決まる）',
    '- `{人}`: 人が確認・判断・入力する処理',
    '- `{外部}`: 顧客・取引先・他社システムなど、こちらで動かせない処理',
    '- `lane` 行の末尾に付けると、そのレーンのノードすべてがその区分になる。ノードは `@レーン` の後ろに付け、ノードの区分がレーンの区分より優先する',
    '- 書類の内容による分岐は、AI が判断するのか（`{AI}`）、明確な条件で判定するのか（`{ルール}`）を必ず書き分ける。ルールで判定できるものを AI に任せない',
    '- 導入後（To-Be）の図では、すべてのノードに区分が付くようにする（レーンに付ければ足りる）',
    '',
    '## 台帳の項目の参照',
    `ラベルの末尾に \`[ID]\` を書くと、その ID を参照として読み、図のラベルからは消します。使える ID は、台帳の項目の ID（${refKinds()} など、一覧にある ID）と、判断マスタ JDG-・テーブル定義 TBL- です。`,
    '- 例: `decision D @承認者 差し戻すか [JDG-003 QA-004]`（判断マスタと、まだ答えのない質問）',
    '- 複数は空白か `,` で区切る。台帳に無い ID を作らない',
    '',
    '## 守ること',
    '- すべてのノードにレーン（`@レーン名`）を付ける。レーンを使わない図なら `lane` 行も `@` も書かない',
    '- レーン名は `lane` 行と一字一句同じにする（空白を含む名前は `@[営業 部]` と書く）',
    '- 1 つの図は 20 ノードまで。超える場合は図を分ける',
    '- 分岐の出口は 2 本か 3 本。差し戻し（前の手順に戻る矢印）も書いてよい',
    '- ラベルの中に `->` や `..>` を書かない。矢印の意味の文字は `→` を使う',
    '- ラベル付きの矢印は 1 行に 1 本だけ書く',
    '- `@` `->` `:` は半角で書く',
  ].join('\n');
}
