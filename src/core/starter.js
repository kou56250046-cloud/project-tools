// 新規の台帳を作る。starterId が null なら空の台帳
export function createLedger(name, starterId, now) {
  const base = emptyLedger(name, now);
  if (!starterId) return base;
  const st = STARTERS[starterId];
  if (!st) throw new Error('不明な案件の型: ' + starterId);
  const r = applyLocalOps(base, [...st.ops, { op: 'project', set: { starter: starterId } }], now);
  if (!r.ok) throw new Error('案件の型の適用に失敗しました: ' + r.errors.join(' / '));
  // 型の項目は「変更」ではないので記録を残さない
  return { ...r.ledger, revision: 0, changelog: [] };
}
