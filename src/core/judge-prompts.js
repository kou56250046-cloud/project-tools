// 差し込み（{{事実一覧}}・{{未回答一覧}}・{{決定事項}}）は、台帳の要件・制約・要望、未回答の質問、有効な決定から作る

import { KINDS, statusLabel } from './schema.js';
import { flowFormatText } from './flow-format.js';

const jpLine = (s) => String(s == null ? '' : s).replace(/\s+/g, ' ').trim();

function judgeFacts(ledger) {
  const xs = ledger.items.filter((it) => (it.kind === 'requirement' && it.status !== 'dropped') || (it.kind === 'constraint') || (it.kind === 'request' && it.status !== 'rejected'));
  return xs.length ? xs.map((it) => `- ${it.id} ${jpLine(it.title)}（${statusLabel(it.kind, it.status)}${it.confidence === 'guess' ? '・推測' : ''}）`).join('\n') : '（まだありません）';
}
function judgeOpenQuestions(ledger) {
  const name = (id) => { const p = ledger.items.find((x) => x.id === id); return p ? p.title : id; };
  const xs = ledger.items.filter((it) => it.kind === 'question' && it.status === 'open');
  return xs.length ? xs.map((it) => `- ${it.id} ${jpLine(it.title)}${it.askTo ? `（聞く相手: ${name(it.askTo)}）` : ''}`).join('\n') : '（まだありません）';
}
function judgeDecisions(ledger) {
  const xs = ledger.items.filter((it) => it.kind === 'decision' && it.status === 'valid');
  return xs.length ? xs.map((it) => `- ${it.id} ${jpLine(it.title)}`).join('\n') : '（まだありません）';
}

const ledgerBlock = (ledger, withFacts = true) => [
  '## 案件の台帳',
  ...(withFacts ? ['### 要望・要件・制約', judgeFacts(ledger), ''] : []),
  '### 未回答の質問', judgeOpenQuestions(ledger),
  ...(withFacts ? ['', '### 決定事項', judgeDecisions(ledger)] : []),
].join('\n');

const P = () => ({ q: KINDS.question.prefix, d: KINDS.decision.prefix, r: KINDS.requirement.prefix, c: KINDS.constraint.prefix });

